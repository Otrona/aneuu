#!/usr/bin/env python3
# embed.py: put the generated parts back into build-hangul-iso.sh:
# the guide pages (docs.py), the F12 panels (cheats.py), han-book and the
# manual text for the F11 book panel, gem, and kfont (kernel console font).   Run from the alpine/ folder.
import sys
sys.path.insert(0, ".")
import docs, cheats

P = "build-hangul-iso.sh"
s = open(P, encoding="utf-8").read()
L = s.split("\n")

def repl(L, start_pat, end_tag, new):
    i = next(k for k, l in enumerate(L) if start_pat in l)
    j = max(k for k, l in enumerate(L) if l == end_tag)
    return L[:i] + new.rstrip("\n").split("\n") + L[j + 1:]

L = repl(L, 'mkdir -p "$STAGE/usr/share/han/doc/ko"', "HANDOC", docs.shell())
L = repl(L, 'mkdir -p "$STAGE/usr/share/han/cheat/ko"', "HANCHEAT", cheats.shell())

book = open("tools/han-book", encoding="utf-8").read().rstrip("\n")
manual = open("tools/aneuu.txt", encoding="utf-8").read().rstrip("\n")
assert "\nHANBOOK\n" not in book and "\nHANMANUAL\n" not in manual
block = ["\t# >>> han-book (generated by tools/embed.py: edit tools/han-book)",
         "\tcat > \"$STAGE/usr/local/bin/hb\" <<'HANBOOK'", *book.split("\n"), "HANBOOK",
         "\tchmod 755 \"$STAGE/usr/local/bin/hb\"",
         "\tln -sf hb \"$STAGE/usr/local/bin/han-book\"   # the old, longer name",
         "\tmkdir -p \"$STAGE/usr/share/han/book\"",
         "\tcat > \"$STAGE/usr/share/han/book/aneuu.txt\" <<'HANMANUAL'", *manual.split("\n"), "HANMANUAL",
         "\t# <<< han-book"]
gem = open("tools/gem", encoding="utf-8").read().rstrip("\n")
assert "\nGEMPY\n" not in gem
gblock = ["\t# >>> gem (generated by tools/embed.py: edit tools/gem)",
          "\tcat > \"$STAGE/usr/local/bin/gem\" <<'GEMPY'", *gem.split("\n"), "GEMPY",
          "\tchmod 755 \"$STAGE/usr/local/bin/gem\"", "\t# <<< gem"]
i = next(k for k, l in enumerate(L) if l.startswith("\t# >>> gem"))
j = next(k for k, l in enumerate(L) if l.startswith("\t# <<< gem"))
L = L[:i] + gblock + L[j + 1:]
kf = open("tools/kfont", encoding="utf-8").read().rstrip("\n")
assert "\nKFONT\n" not in kf
kblock = ["\t# >>> kfont (generated by tools/embed.py: edit tools/kfont)",
          "\tcat > /tmp/kfont <<'KFONT'", *kf.split("\n"), "KFONT", "\t# <<< kfont"]
i = next(k for k, l in enumerate(L) if l.startswith("\t# >>> kfont"))
j = next(k for k, l in enumerate(L) if l.startswith("\t# <<< kfont"))
L = L[:i] + kblock + L[j + 1:]
hk = open("tools/hkb", encoding="utf-8").read().rstrip("\n")
assert "\nHKB\n" not in hk
hblock = ["\t# >>> hkb (generated by tools/embed.py: edit tools/hkb)",
          "\tcat > \"$STAGE/usr/local/bin/hkb\" <<'HKB'", *hk.split("\n"), "HKB", "\t# <<< hkb"]
i = next(k for k, l in enumerate(L) if l.startswith("\t# >>> hkb"))
j = next(k for k, l in enumerate(L) if l.startswith("\t# <<< hkb"))
L = L[:i] + hblock + L[j + 1:]
i = next(k for k, l in enumerate(L) if l.startswith("\t# >>> han-book"))
j = next(k for k, l in enumerate(L) if l.startswith("\t# <<< han-book"))
L = L[:i] + block + L[j + 1:]
open(P, "w", encoding="utf-8").write("\n".join(L).rstrip("\n") + "\n")
print("embedded: docs, cheats, han-book, manual, gem, kfont, hkb")
